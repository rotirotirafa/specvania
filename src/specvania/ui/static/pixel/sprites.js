/** Original specvania art, authored as pixels for T15 (2026-10-12).
 * No game, asset pack, downloaded image or generated raster is used.
 * Every frame is a 16 by 16 array of palette symbols; '.' is transparent.
 * States contain ordered frame lists. Texture keys are name:state:index.
 * The gallery intentionally presents every pose without motion for review.
 */
function freezeSprites(sprites) {
  for (const states of Object.values(sprites)) {
    for (const frames of Object.values(states)) {
      for (const frame of frames) Object.freeze(frame);
      Object.freeze(frames);
    }
    Object.freeze(states);
  }
  return Object.freeze(sprites);
}

